/** The format reference inside the prompt. Comments after `<-` are for the reader only. */
const FORMAT_REFERENCE = [
  '%%orbit:v1                      <- line 1, exactly this. Nothing before it.',
  'flowchart LR                    <- line 2, always this.',
  '  %%orbit roadmap "Name"        <- optional, once. Name in double quotes. Leave it out when importing into an open roadmap.',
  '  %%orbit band <key> {"name":"Week 1","start":"2026-11-21","end":"2026-11-27"}',
  '                                <- optional. "name" required. "start"/"end" optional, YYYY-MM-DD. A band groups nodes (a stage or period).',
  '  %%orbit node <key> {"kind":"task","ref":"<uuid>","x":120,"y":40,"band_id":"<band key>"}',
  '                                <- one per node, before or after its shape line. Every field optional.',
  '                                   kind: only to override the :::class (must match it). ref: UUID of an existing row, else leave out.',
  '                                   x,y: canvas position, numbers. band_id: a band <key> declared in this text.',
  '  %%orbit edge <from> -> <to> {"kind":"then","label":"yes","taken":true}',
  '                                <- optional, <from>/<to> are node keys. kind default "then". label optional. taken: only on a decision\'s edge, at most one per decision.',
  '  <key>["Title"]:::task         <- REQUIRED shape line for every node. Quote the title as a JSON string ("" with \\" escapes).',
  '  <key>{"Title"}:::decision     <- decisions use braces. :::class is one of the node kinds.',
  '  <from> --> <to>               <- optional Mermaid arrow = a "then" edge. <from> -- yes --> <to> adds a label.',
].join('\n')

const fence = (lang: string, body: string) => ['```' + lang, body, '```'].join('\n')

/** The "Copy for AI" prompt: the format, the closed kind lists, rules, worked examples, a checklist and the existing rows an AI may reference. */
export function roadmapPrompt(areas: Row[], projects: Row[], goals: Row[], tasks: Row[]): string {
  const list = (rows: Row[]) => rows.map((row) => `- ${row.title} (id ${row.id})`).join('\n') || '- none'
  return [
    'You are helping me plan with Orbit. An Orbit roadmap is a graph of steps: tasks, goals, milestones, decisions with labelled branches, notes and headings, optionally framed in bands. You will write it as code that Orbit can import.',
    '',
    '## Step 1: ask me questions first. Do not write the roadmap yet.',
    'Ask your questions in one short numbered list, wait for my answers, then ask follow-ups only if something important is still unclear. Suggested questions (skip any I already answered):',
    '1. Goal: what should be true when this roadmap is finished?',
    '2. Deadline: is there a date, or a rough time budget (for example 6 weeks, a few hours a week)?',
    '3. Scope: what is in, and what is explicitly out?',
    '4. Phases: does the work fall into stages or periods (these become bands: "Week 1", "Phase: Research")? Which ones, with dates if known?',
    '5. Dependencies: which steps cannot start until another one is done? Is anything blocked by something outside my control?',
    '6. Decisions: are there forks where I must choose a path (for example "funded or not?")? What are the options, and is any already decided?',
    '7. Existing items: which tasks, projects or goals below should be reused instead of duplicated?',
    '8. Layout: do I prefer the flow left to right, top to bottom, or something else?',
    'You may assume defaults, and say so in one line when you do, only for details that do not change the plan: positions (leave out x and y), the direction (left to right), undated bands, and the roadmap name (use my goal in a few words). Do NOT assume the goal, the deadline, the phases, dependencies or decisions: ask. If I say "just do it", assume everything and list your assumptions in one line before the code.',
    '',
    '## Step 2: once you have enough, reply with the roadmap',
    'Reply with a single fenced code block and nothing else. Use exactly this format, version %%orbit:v1.',
    '',
    '## Format reference (annotated; the `<-` comments are explanation, never copy them into your answer)',
    fence('text', FORMAT_REFERENCE),
    '',
    '## Kinds (closed lists)',
    '- Node kinds, closed list: task, project, goal, milestone, decision, note, text, heading. Omit any other type.',
    '- task: a real item. Without "ref" a new task is created from the title; with "ref" it points at an existing task from the lists below.',
    '- project, goal, milestone: only valid with "ref" set to an existing row from the lists below (they cannot be created here). If none exists, use a task or note instead.',
    '- decision: a fork. Its outgoing edges are the branches; label each one.',
    '- note: a free-text card that is not a task (a reminder, an assumption). heading: a bold title for a region of the map (for example "Admissions"). text: plain text placed on the canvas.',
    '- Band: a labelled frame drawn around a group of nodes, so one stage of the plan reads as one block. Examples: "Week 1", "Phase: Research", "Before launch". It can have a start and end date (then it shows on the timeline and its progress counts the tasks inside it). It only frames its members, so it works in any layout.',
    '- Edge kinds, closed list: then, blocks, depends_on, decides. Use `then` when unsure.',
    '- then: a plain next step, "this, then that". blocks: the source must be finished before the target can start. depends_on: the source needs the target done first (the reverse of blocks). decides: a branch leaving a decision; give it a label such as "yes" or "funded".',
    '- Use a decision when the plan really forks and I have to pick one way. Use a note for context. Use a band only for a real stage or period, not for a single step.',
    '',
    '## Rules',
    '- Node keys and band keys are identifiers: letters, digits, underscores only, unique within their kind. Not UUIDs, not words with spaces or dashes.',
    '- Every node needs a `%%orbit node <key> {...}` line (use {} if nothing to set) and a shape line `<key>["Title"]:::<kind>` (decision: `<key>{"Title"}:::decision`).',
    '- A node with no :::class and no "kind" becomes a note. Always write the class.',
    '- A decision has one edge per branch; set "taken":true on at most one of its outgoing edges, only when the answer is already known. Never on a non-decision.',
    '- Bands are optional. "start" and "end" are YYYY-MM-DD dates, "end" not before "start"; leave both out for an undated stage. Put a node in a band with "band_id":"<band key>"; the band must be declared in the same text.',
    '- "ref" must be the id (UUID) of an existing row listed below. Never invent ids, never put a key or a title there. Do not repeat a row that already exists.',
    '- Do not write "id" on nodes, bands or edges: ids are for exported files. Leave them out.',
    '- Positions: x and y are optional numbers, anywhere on the canvas, negative allowed. A node is 240 wide and 64 tall: keep nodes at least 80 apart. The flow may run in any direction (left to right, top to bottom, upward, leftward); edges may point backward or loop. Use about 320 between columns and 120 between rows for a left-to-right plan, 280 and 140 for top to bottom. Leave x and y out if unsure.',
    '- Arrows: every edge endpoint must be a declared node key. An edge line and a Mermaid arrow with the same endpoints are one edge (the arrow supplies the label).',
    '',
    '## Do / Do not',
    '- DO start with `%%orbit:v1` then `flowchart LR`. DO indent lines with two spaces. DO use double quotes in JSON.',
    "- DO keep titles short (under about 60 characters) and in the user's language.",
    '- DO NOT add any other `%%` line or comment: any unknown `%%` line is an error, and so is a `%%` comment.',
    '- DO NOT use Mermaid features beyond the shapes and arrows above (no subgraph, style, classDef, click, or other shapes).',
    '- DO NOT add trailing commas, single quotes or extra JSON fields: unknown fields are errors.',
    '- DO NOT wrap the answer in prose. One code block, nothing before or after it.',
    '',
    '## Example 1: a small plan (two bands, tasks, a note)',
    fence('orbit', EXAMPLE_PLAN),
    '',
    '## Example 2: a branching plan (heading, decision with a taken branch, blocks and depends_on edges)',
    fence('orbit', EXAMPLE_BRANCH),
    '',
    '## Check your output before replying',
    '- [ ] First line is `%%orbit:v1`, second is `flowchart LR`, nothing else precedes them.',
    '- [ ] Every node has both a `%%orbit node` line and a shape line, with matching keys.',
    '- [ ] Every shape line ends in :::kind with a kind from the closed list.',
    '- [ ] Every edge and arrow endpoint is a declared node key; every band_id is a declared band key.',
    '- [ ] At most one "taken":true per decision, and only on edges that leave a decision.',
    '- [ ] Dates are YYYY-MM-DD. Every "ref" is a UUID copied from the lists below, or absent.',
    '- [ ] No comments, no extra fields, no trailing commas. The reply is one fenced code block only.',
    '',
    'Areas (parent=<id> on the roadmap line is informational; an import never moves a roadmap):',
    list(areas),
    '',
    'Projects:',
    list(projects),
    '',
    'Goals:',
    list(goals),
    '',
    'Open tasks:',
    list(tasks),
  ].join('\n')
}
